/**
 * Minimal localization table for the small set of UI strings the template owns
 * (everything else comes from the appindex.json). Falls back to English when a
 * locale isn't covered here — the app's content remains correctly localized
 * either way.
 */

export interface UIStrings {
  selectLanguage: string;
  choosePlatform: string;
  screenshotViewer: string;
  closeDialog: string;
  previousScreenshot: string;
  nextScreenshot: string;
  previousPlatform: string;
  nextPlatform: string;
  themeLabel: string;
  themeAuto: string;
  appleStoreBadge: string;
  googleStoreBadge: string;

  about: string;
  permissions: string;
  releaseNotes: string;
  rawKeyLabel: string;
  whyNoDescription: string;
  noPermissions: string;
  versionLabel: string;
  buildLabel: string;
  bundleIdLabel: string;
  appIdLabel: string;
  privacyLink: string;
  supportLink: string;
  dependenciesLabel: string;
  /** Pagefind search input placeholder. */
  searchPlaceholder: string;
  /** Pagefind "clear search" affordance. */
  searchClearLabel: string;
  /** Pagefind empty-results message; "[SEARCH_TERM]" is interpolated. */
  searchZeroResults: string;
  /** Footer label preceding the site-generation timestamp. */
  generatedLabel: string;
  /** Footer link to the project's source repository. */
  sourceLink: string;
  /** Footer link to the project's latest release. */
  releaseLink: string;
  /** Footer attribution beside the Day mark. Carries the product name, because word order
      around it differs by language. */
  builtWith: string;
  /** Heading of the per-platform download card. */
  downloadHeading: string;
  /** Hero button that opens the hosted web-dom build. */
  openWebApp: string;
  /** Header/nav link to the screenshot gallery page. */
  galleryLink: string;
  /** Landing-page row labels for Android's device profiles (Apple's are proper nouns). */
  deviceHandset: string;
  deviceTablet: string;
  /** Gallery page heading. */
  galleryHeading: string;
  /** Gallery page subtitle; "[DAYSCRIPT]" is interpolated — the docs link in the visible
      subtitle, the bare word in the page description. */
  galleryBlurb: string;
  /** Theme switcher labels. */
  themeLight: string;
  themeDark: string;
  /** The toolbar QR code's accessible name and overlay title; "[APP]" is the app's name. */
  qrTitle: string;
  /** Under the full-screen QR code: what scanning it does. */
  qrHint: string;
  /** Accessible name of the build-channel picker above the platform picker (lib/channels.ts). */
  versionPickerLabel: string;
  /** The one-line notice on a development channel's pages; "[BRANCH]" is the branch the build
      came from. One string rather than a heading and a body: it has to read as a single
      sentence on one line, and splitting a sentence in two breaks word order in translation. */
  devBuildInline: string;
  /** The notice's link to the released version; "[VERSION]" is that version. */
  devBuildReleaseLink: string;
  /** The notice's second line when the project has published no release at all. */
  devBuildNoRelease: string;
  /** Under a development channel's download card: where those packages came from. */
  devBuildDownloadNote: string;
  /** About-card row naming the commit a development build came from. */
  commitLabel: string;
}

