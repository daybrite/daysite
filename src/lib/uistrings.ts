export function uiStrings(locale: string): UIStrings {
  // English first, then each subtag prefix from broadest to narrowest, so the more specific
  // table always wins the key: "zh-Hant-TW" picks up "zh" and then "zh-Hant". The order is the
  // whole point — apply "zh" last and Traditional Chinese pages render the Simplified strings.
  const parts = locale.split('-');
  let out: UIStrings = { ...EN };
  for (let i = 1; i <= parts.length; i++) {
    out = { ...out, ...(TABLES[parts.slice(0, i).join('-')] ?? {}) };
  }
  return out;
}
